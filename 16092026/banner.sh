#!/bin/bash

# Проверяем, передан ли аргумент (строка текста)
if [ -z "${1}" ]; then
    echo "Использование: $0 \"Ваш текст\""
    exit 1
fi

text="${1}"
# Считаем длину строки с помощью встроенных средств bash
length=${#text}

# Формируем горизонтальную линию из дефисов нужной длины
# Добавляем +2, так как внутри рамки есть по одному пробелу по бокам от текста
printf -v border '%*s' "$((length + 2))" ''
border=${border// /-}

# Выводим баннер
echo "+${border}+"
echo "| ${text} |"
echo "+${border}+"
